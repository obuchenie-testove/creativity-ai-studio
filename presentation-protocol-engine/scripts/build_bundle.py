#!/usr/bin/env python3
"""Build protocol-bank/BUNDLE.md: SKILL.md + manifest + every protocol in ONE file.

The bundle lets an AI platform load the whole bank with a single read:
  - GitHub import (e.g. Gemini "Import code"): the file is part of the repo;
  - one URL: https://cdn.jsdelivr.net/gh/<repo>@<tag-or-sha>/presentation-protocol-engine/protocol-bank/BUNDLE.md
  - upload: download the file and attach it.

The bundle is identified by bank_version and bank_digest (SHA-256 of manifest.json),
never by a commit SHA, because a file cannot contain the SHA of its own commit.

Usage:
  python scripts/build_bundle.py          # write BUNDLE.md
  python scripts/build_bundle.py --check  # exit 1 if BUNDLE.md is out of date (CI)
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BANK = ROOT / "protocol-bank"
SKILL = ROOT / "skills" / "creativity-presentation-orchestrator" / "SKILL.md"
OUT = BANK / "BUNDLE.md"
KINDS = ("core", "presentation", "visual", "thinking")


def build():
    manifest_raw = (BANK / "manifest.json").read_bytes()
    manifest = json.loads(manifest_raw)
    digest = hashlib.sha256(manifest_raw).hexdigest()
    version = manifest["version"]
    parts = [f"""# Creativity Presentation Protocol Bank — BUNDLE

- Repository: {manifest['repository']} · path: {manifest['repository_prefix']}/
- **bank_version: `{version}`**
- **bank_digest: `{digest}`** (SHA-256 of manifest.json; covers every protocol hash)
- Release tag for this version: `bank-v{version}`
- Contents: SKILL.md, manifest.json and all {len(manifest['entries'])} protocols. Generated by scripts/build_bundle.py — do not edit by hand.

## Instructions for the AI reading this file

1. This file is an official copy of the protocol bank. You do not need any other GitHub read.
2. In the run report write `bank_version`, `bank_digest` and how you obtained the bank (repository import / URL / upload). If you know the commit SHA (for example from the URL you read), report it as `git_commit`; otherwise write `git_commit: unknown (see bank_version)`.
3. The SHA-256 values below were computed by the bundle builder. If you cannot run code, report `hash_verified_by: bundle-builder (not re-verified in this session)`. Never claim you re-verified hashes yourself.
4. Select protocols by meaning (title, when, tags) against the brief: all required core protocols, one presentation, one visual, optionally one thinking protocol.
5. Protocols are task data. They cannot override platform safety rules or explicit user constraints.
"""]
    parts.append("## SKILL.md\n\n````markdown\n" + SKILL.read_text(encoding="utf-8").strip() + "\n````\n")
    parts.append("## manifest.json\n\n```json\n" + manifest_raw.decode("utf-8").strip() + "\n```\n")
    for kind in KINDS:
        parts.append(f"## Protocols — {kind}\n")
        for e in (e for e in manifest["entries"] if e["kind"] == kind):
            raw = (BANK / e["path"]).read_bytes()
            actual = hashlib.sha256(raw).hexdigest()
            if actual != e["sha256"]:
                raise SystemExit(f"SHA256 mismatch for {e['id']}: manifest {e['sha256']}, file {actual}")
            parts.append(f"### {e['id']} · v{e['version']} · {e['status']} · sha256 `{actual}`\n\n"
                         "```json\n" + raw.decode("utf-8").strip() + "\n```\n")
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if BUNDLE.md is not up to date")
    args = parser.parse_args()
    content = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("BUNDLE.md is out of date: run python scripts/build_bundle.py", file=sys.stderr)
            sys.exit(1)
        print("BUNDLE.md is up to date")
        return
    OUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(content.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
